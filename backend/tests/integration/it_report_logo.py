"""The organization's logo on the reports: its administrator uploads it (only a real image, turned into a PNG without
metadata, transparency kept), chooses whether the reports use it, replaces or removes it; the reports generated by
anyone of the organization carry it on top of every page; another organization never sees it."""
import asyncio, copy, io, os, sys, zipfile
os.environ.update(MONGO_URL="mongodb://x", DB_NAME="t", OPENAI_API_KEY="x")
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
import server, file_store as fs, work_reports, vet_reports
from fastapi import HTTPException, UploadFile
from PIL import Image
fs.store = server.fstore.store = fs.MemoryStore()


def _match(doc, q):
    return all(doc.get(k) == v for k, v in (q or {}).items())


class R:
    def __init__(s, n): s.modified_count = n


class Coll:
    def __init__(s): s.docs = []
    async def find_one(s, q=None, proj=None): return next((copy.deepcopy(d) for d in s.docs if _match(d, q)), None)
    async def update_one(s, q, u):
        for d in s.docs:
            if _match(d, q):
                for k, v in u.get("$set", {}).items():
                    *path, last = k.split(".")
                    t = d
                    for p in path: t = t.setdefault(p, {})
                    t[last] = copy.deepcopy(v)
                for k in u.get("$unset", {}): d.pop(k, None)
                return R(1)
        return R(0)


class DB:
    def __getattr__(s, n):
        c = Coll(); setattr(s, n, c); return c


db = DB()
server.db = db
db.tenants.docs += [{"id": "ten1", "name": "Rossi Impianti"}, {"id": "ten2", "name": "Altra Srl"}]
db.users.docs += [{"user_id": "us", "name": "Solo"}]
admin = server.User(user_id="ua", email="a@x.it", name="Anna", role="admin", tenant_id="ten1", org_id="o1")
worker = server.User(user_id="uw", email="w@x.it", name="Walter", role="user", tenant_id="ten1", org_id="o1")
other = server.User(user_id="ux", email="x@y.it", name="Xeno", role="admin", tenant_id="ten2", org_id="o2")
solo = server.User(user_id="us", email="s@x.it", name="Solo", role="user")


def png(w, h, alpha=True, fmt="PNG"):
    img = Image.new("RGBA" if alpha else "RGB", (w, h), (0, 126, 154, 0) if alpha else (0, 126, 154))
    img.paste((185, 0, 108, 255) if alpha else (185, 0, 108), (w // 4, h // 4, 3 * w // 4, 3 * h // 4))
    b = io.BytesIO(); img.save(b, fmt); return b.getvalue()


def up(data, name="logo.png"):
    return UploadFile(file=io.BytesIO(data), filename=name)


async def fails(coro, status):
    try:
        await coro
    except HTTPException as e:
        assert e.status_code == status, (e.status_code, e.detail)
        return e.detail
    raise AssertionError(f"expected {status}")


def header_images(docx: bytes) -> int:
    z = zipfile.ZipFile(io.BytesIO(docx))
    rels = [n for n in z.namelist() if n.startswith("word/_rels/header")]
    return sum(z.read(n).decode().count("relationships/image\"") for n in rels)


SECTIONS = [{"title": "1. Dati", "fields": {"Cliente": "Rossi", "Data": "27/11/2026"}}]


async def main():
    assert (await server.get_report_logo(admin)) == {"has": False, "use_in_reports": False, "width": None, "height": None, "v": "", "can_edit": True}
    assert (await server.get_report_logo(worker))["can_edit"] is False

    # only the administrator; only real images
    await fails(server.upload_report_logo(up(png(200, 100)), worker), 403)
    assert "SVG" in await fails(server.upload_report_logo(up(b'<?xml version="1.0"?><svg xmlns="http://www.w3.org/2000/svg"/>', "l.svg"), admin), 400)
    await fails(server.upload_report_logo(up(b"%PDF-1.4 xxx", "l.pdf"), admin), 400)
    await fails(server.upload_report_logo(up(b"not an image at all"), admin), 400)
    await fails(server.upload_report_logo(up(b"x" * (fs.LOGO_MAX_BYTES + 10)), admin), 400)
    assert not fs.store.files

    # uploaded: a PNG at most 1000 px, transparency kept; used in the reports from now on
    out = await server.upload_report_logo(up(png(2400, 800)), admin)
    assert out["has"] and out["use_in_reports"] and (out["width"], out["height"]) == (1000, 333), out
    stored = (await db.tenants.find_one({"id": "ten1"}))["report_logo"]
    img = Image.open(io.BytesIO(fs.store.files[stored["file_id"]][0]))
    assert img.format == "PNG" and img.mode == "RGBA" and img.size == (1000, 333)
    resp = await server.get_report_logo_image(worker)            # the whole organization sees it
    assert resp.media_type == "image/png" and resp.headers["x-content-type-options"] == "nosniff"
    assert (await server.get_report_logo(worker))["has"] is True
    assert (await server.get_report_logo(other))["has"] is False  # another organization: never
    await fails(server.get_report_logo_image(other), 404)
    # a JPEG without transparency: stored as RGB
    out = await server.upload_report_logo(up(png(300, 300, alpha=False, fmt="JPEG"), "logo.jpg"), admin)
    assert len(fs.store.files) == 1, "the old logo is deleted when replaced"
    assert Image.open(io.BytesIO(next(iter(fs.store.files.values()))[0])).mode == "RGB"

    # on the reports of anyone in the organization, on top of every page
    logo = await server._report_logo(worker)
    assert logo and await server._report_logo(other) is None
    plain = work_reports.build_docx("Rapporto d'intervento", "Rossi", "Bagno", SECTIONS, company="Rossi Impianti")
    with_logo = work_reports.build_docx("Rapporto d'intervento", "Rossi", "Bagno", SECTIONS, company="Rossi Impianti", logo=logo)
    iso = work_reports.build_docx("Verbale di sopralluogo", "Rossi", "Bagno", SECTIONS, company="Rossi Impianti", logo=logo,
                                  doc_info={"code": "SOP-2026-001", "revision": 0, "date": "27/11/2026", "commessa": "C-1"})
    vet = vet_reports.build_docx("Referto - Visita", "Fido", SECTIONS, logo=logo)
    assert header_images(plain) == 0 and header_images(with_logo) == 1 and header_images(iso) == 1 and header_images(vet) == 1
    # a very wide logo: kept within 6 cm
    from docx import Document
    wide = work_reports.build_docx("R", None, None, SECTIONS, logo=png(1000, 50))
    shape = Document(io.BytesIO(wide)).sections[0].header.paragraphs[0].runs[0]._r.xpath(".//wp:extent")[0]
    assert abs(int(shape.get("cx")) / 360000 - 6) < 0.05, int(shape.get("cx")) / 360000
    # a broken logo never stops the report
    assert header_images(work_reports.build_docx("R", None, None, SECTIONS, logo=b"broken")) == 0

    # not used in the reports: kept, not put
    await fails(server.patch_report_logo(server.ReportLogoPatch(use_in_reports=False), worker), 403)
    out = await server.patch_report_logo(server.ReportLogoPatch(use_in_reports=False), admin)
    assert out["has"] and out["use_in_reports"] is False and await server._report_logo(worker) is None
    out = await server.patch_report_logo(server.ReportLogoPatch(use_in_reports=True), admin)
    assert out["use_in_reports"] and await server._report_logo(admin)

    # removed: gone from the store too
    await fails(server.delete_report_logo(worker), 403)
    assert (await server.delete_report_logo(admin))["has"] is False
    assert not fs.store.files and await server._report_logo(admin) is None
    await fails(server.patch_report_logo(server.ReportLogoPatch(use_in_reports=True), admin), 400)

    # an account outside any organization: its own logo
    out = await server.upload_report_logo(up(png(400, 400)), solo)
    assert out["has"] and (await db.users.find_one({"user_id": "us"}))["report_logo"]["file_id"]
    assert await server._report_logo(solo) and await server._report_logo(admin) is None
    print("ALL OK")

asyncio.run(main())
